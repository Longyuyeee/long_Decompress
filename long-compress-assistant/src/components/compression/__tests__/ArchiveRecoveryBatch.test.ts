import { beforeEach, describe, expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import { createPinia, getActivePinia, setActivePinia } from 'pinia'
import { ARCHIVE_RECOVERY_DRAFT_KEY, useArchiveRecoveryStore } from '@/composables/useArchiveRecoveryBatch'
import ArchiveRecoveryBatch from '../ArchiveRecoveryBatch.vue'
import { useTaskStore } from '@/stores/task'
const mocks = vi.hoisted(() => ({group:vi.fn(),diagnose:vi.fn(),repair:vi.fn(),cancelDiagnosis:vi.fn(),cancelRepair:vi.fn(),invoke:vi.fn(),open:vi.fn()}))
vi.mock('@tauri-apps/api/tauri', () => ({invoke:mocks.invoke}))
vi.mock('@tauri-apps/api/dialog', () => ({open:mocks.open}))
vi.mock('@/composables/useTauriCommands', () => ({useTauriCommands:() => ({groupArchiveDiagnosisSources:mocks.group,diagnoseArchive:mocks.diagnose,repairArchiveBatchItem:mocks.repair,cancelArchiveDiagnosis:mocks.cancelDiagnosis,cancelZipRepair:mocks.cancelRepair})}))
const report = (format:string, status:string, canRepair:boolean) => ({filePath:'',fileSize:4000,actualFormat:format,status,encrypted:true,splitArchive:format==='RAR',volumesFound:2,missingVolumes:[],totalFiles:1,totalDirectories:0,totalUncompressedSize:100,totalUncompressedSizeKnown:true,integrityTested:false,canRepair,recoverability:'repairable',issues:[],evidence:[]})
function setup() {
  const pinia=createPinia(); setActivePinia(pinia)
  return mount(ArchiveRecoveryBatch,{props:{paths:['C:/a.part1.rar','C:/a.part2.rar','C:/b.zip']},global:{plugins:[pinia],stubs:{Teleport:true,Transition:false}}})
}
beforeEach(() => {
  vi.clearAllMocks(); Object.values(mocks).forEach(mock => mock.mockReset()); localStorage.clear()
  mocks.invoke.mockImplementation(async command => command==='load_app_settings' ? '{}' : undefined)
  mocks.group.mockResolvedValue([{path:'C:/a.part1.rar',selectedMembers:2},{path:'C:/b.zip',selectedMembers:1}])
  mocks.diagnose.mockImplementation(async (_id,path,password) => path.endsWith('.rar') ? report('RAR',password ? 'damaged' : 'password_required',!!password) : report('ZIP','directory_lost',true))
})
describe('archive batch recovery user flow', () => {
  it('recognizes missing-disk rescue and shows folded result details in the expanded row', async () => {
    mocks.group.mockResolvedValue([{path:'C:/parts.zip',selectedMembers:2}])
    mocks.diagnose.mockResolvedValue({...report('ZIP','partial_recovery',true),missingVolumes:['parts.z02'],recoverability:'missing_volume_entries'})
    const wrapper = setup(); await flushPromises()
    await wrapper.get('[data-testid="batch-diagnose"]').trigger('click'); await flushPromises()
    expect(wrapper.get('[data-testid="archive-batch-status"]').text()).toContain('缺卷，可部分救援')
    mocks.open.mockResolvedValue('D:/recovered')
    mocks.repair.mockResolvedValue({outputPath:'D:/recovered/parts.zip',recoveredFiles:1,recoveredDirectories:0,recoveredEntries:['资料/说明.txt'],skippedEntries:['图片.bin：缺少 parts.z02'],partial:true,verified:true,directoryRebuilt:false,outputEncrypted:false})
    await wrapper.get('[data-testid="batch-repair"]').trigger('click'); await flushPromises()
    expect(wrapper.get('[data-testid="archive-batch-detail"]').exists()).toBe(true)
    expect(wrapper.get('[data-testid="recovery-file-details"]').text()).toContain('资料/说明.txt')
    expect(wrapper.get('[data-testid="recovery-skipped-details"]').attributes('open')).toBeUndefined()
    expect(wrapper.get('[data-testid="archive-batch-result"]').classes()).toContain('bg-amber-500/5')
    wrapper.unmount()
  })
  it('groups volumes, expands individual rows and keeps bulk configuration inside a dialog', async () => {
    const wrapper=setup(); await flushPromises()
    expect(wrapper.findAll('[data-testid="archive-batch-row"]')).toHaveLength(2)
    expect(wrapper.text()).toContain('已合并 2 个所选卷')
    expect(wrapper.find('[data-testid="archive-batch-config-dialog"]').exists()).toBe(false)
    await wrapper.findAll('[data-testid="archive-batch-expand"]')[0].trigger('click')
    expect(wrapper.find('[data-testid="archive-batch-detail"]').exists()).toBe(true)
    const all=wrapper.get('input[aria-label="选择全部压缩包"]')
    await all.setValue(false)
    expect(wrapper.get('[data-testid="batch-diagnose"]').attributes('disabled')).toBeDefined()
    await all.setValue(true)
    expect(wrapper.get('[data-testid="batch-diagnose"]').attributes('disabled')).toBeUndefined()
    await wrapper.get('[data-testid="batch-recovery-config"]').trigger('click')
    expect(wrapper.get('[data-testid="archive-batch-config-dialog"]').text()).toContain('共用原包密码')
    wrapper.unmount()
  })
  it('continues after a repair failure and queues a successful result once with its repair password and chosen extraction directory', async () => {
    const wrapper=setup(); await flushPromises()
    await wrapper.get('[data-testid="batch-diagnose"]').trigger('click'); await flushPromises()
    expect(mocks.diagnose).toHaveBeenCalledTimes(2)
    await wrapper.get('[data-testid="batch-recovery-config"]').trigger('click')
    const dialog=wrapper.get('[data-testid="archive-batch-config-dialog"]')
    await dialog.findAll('input[type="checkbox"]')[0].setValue(true)
    await dialog.get('[data-testid="archive-batch-shared-password"]').setValue('shared secret')
    await dialog.get('[data-testid="archive-batch-output"]').setValue('D:/repair')
    await dialog.findAll('input[type="checkbox"]')[1].setValue(true)
    await dialog.get('input[placeholder="留空则使用各自原包目录"]').setValue('D:/extract')
    await wrapper.get('[data-testid="archive-batch-config-apply"]').trigger('click')
    await wrapper.get('[data-testid="batch-diagnose"]').trigger('click'); await flushPromises()
    mocks.repair.mockRejectedValueOnce(new Error('恢复卷不足')).mockResolvedValueOnce({outputPath:'D:/repair/b/已恢复.zip',recoveredFiles:1,recoveredDirectories:0,skippedEntries:[],verified:true,partial:true,directoryRebuilt:true,outputEncrypted:true})
    await wrapper.get('[data-testid="batch-repair"]').trigger('click'); await flushPromises()
    expect(mocks.repair).toHaveBeenCalledTimes(2)
    expect(mocks.repair.mock.calls[1].slice(1)).toEqual(['C:/b.zip','D:/repair','ZIP','shared secret'])
    expect(wrapper.text()).toContain('处理未完成')
    expect(wrapper.text()).toContain('已恢复 1 个文件')
    await wrapper.get('[data-testid="archive-batch-password"]').setValue('later password')
    await wrapper.get('[data-testid="batch-queue-recovered"]').trigger('click'); await flushPromises()
    expect(useTaskStore().tasks).toHaveLength(1)
    expect(useTaskStore().tasks[0]).toMatchObject({sourceFiles:['D:/repair/b/已恢复.zip'],password:'shared secret',outputPath:'D:/extract',status:'pending'})
    expect(wrapper.get('[data-testid="batch-queue-recovered"]').attributes('disabled')).toBeDefined()
    wrapper.unmount()
  })
  it('keeps same-name archives from separate sources in different extraction directories', async () => {
    mocks.group.mockResolvedValue([{path:'C:/one/data.zip',selectedMembers:1},{path:'C:/two/data.zip',selectedMembers:1}])
    const wrapper=setup(); await flushPromises()
    await wrapper.get('[data-testid="batch-recovery-config"]').trigger('click')
    const dialog=wrapper.get('[data-testid="archive-batch-config-dialog"]')
    await dialog.get('[data-testid="archive-batch-output"]').setValue('D:/repair')
    await dialog.findAll('input[type="checkbox"]')[1].setValue(true)
    await dialog.get('input[placeholder="留空则使用各自原包目录"]').setValue('D:/extract')
    await wrapper.get('[data-testid="archive-batch-config-apply"]').trigger('click')
    await wrapper.get('[data-testid="batch-diagnose"]').trigger('click'); await flushPromises()
    mocks.repair.mockResolvedValueOnce({outputPath:'D:/repair/one/data.zip',recoveredFiles:1,skippedEntries:[],outputEncrypted:false}).mockResolvedValueOnce({outputPath:'D:/repair/two/data.zip',recoveredFiles:1,skippedEntries:[],outputEncrypted:false})
    await wrapper.get('[data-testid="batch-repair"]').trigger('click'); await flushPromises()
    await wrapper.get('[data-testid="batch-queue-recovered"]').trigger('click')
    const outputs=useTaskStore().tasks.map(task=>task.outputPath)
    expect(new Set(outputs).size).toBe(2); expect(outputs.every(output=>output.startsWith('D:/extract/'))).toBe(true)
    wrapper.unmount()
  })

  it('stops the active check and leaves later groups untouched', async () => {
    let rejectActive:(value:Error)=>void=()=>{}
    mocks.diagnose.mockImplementation(() => new Promise((_resolve,reject) => {rejectActive=reject}))
    mocks.cancelDiagnosis.mockImplementation(async () => {rejectActive(new Error('cancelled'))})
    const wrapper=setup(); await flushPromises()
    await wrapper.get('[data-testid="batch-diagnose"]').trigger('click'); await flushPromises()
    await wrapper.get('[data-testid="batch-stop"]').trigger('click'); await flushPromises()
    expect(mocks.diagnose).toHaveBeenCalledTimes(1)
    expect(mocks.cancelDiagnosis).toHaveBeenCalledOnce()
    expect(wrapper.text()).toContain('已停止，可重试')
    expect(wrapper.findAll('[data-testid="archive-batch-status"]')[1].text()).toBe('待检查')
    wrapper.unmount()
  })

  it('retains the current list, independent settings and passwords when the page is recreated without starting work', async () => {
    const wrapper=setup(); await flushPromises()
    const store=useArchiveRecoveryStore()
    store.update(store.rows[0],{password:'only in memory',outputDirectory:'D:/mine'})
    store.rows[0].expanded=true
    const id=store.rows[0].id, pinia=getActivePinia()!
    wrapper.unmount()
    const reopened=mount(ArchiveRecoveryBatch,{props:{paths:[...store.sourcePaths]},global:{plugins:[pinia],stubs:{Teleport:true,Transition:false}}})
    await flushPromises()
    expect(store.rows[0]).toMatchObject({id,password:'only in memory',outputDirectory:'D:/mine',expanded:true})
    expect(mocks.group).toHaveBeenCalledOnce()
    expect(mocks.diagnose).not.toHaveBeenCalled()
    expect(localStorage.getItem(ARCHIVE_RECOVERY_DRAFT_KEY)).not.toContain('only in memory')
    reopened.unmount()
  })

  it('offers restart recovery without passwords or automatic work, requires recheck and separately requests the recovered result password', async () => {
    setActivePinia(createPinia())
    const old=useArchiveRecoveryStore()
    await old.load(['C:/a.rar','C:/b.zip'])
    old.update(old.rows[0],{password:'original password',outputDirectory:'D:/repair',extractDirectory:'D:/extract'})
    old.update(old.rows[1],{password:'original password',outputDirectory:'D:/repair'})
    await old.check()
    mocks.repair.mockResolvedValueOnce({outputPath:'D:/repair/a.rar',recoveredFiles:1,skippedEntries:[],outputEncrypted:true})
      .mockRejectedValueOnce(new Error('文件损坏'))
    await old.repair('D:/repair')
    expect(localStorage.getItem(ARCHIVE_RECOVERY_DRAFT_KEY)).not.toContain('original password')
    vi.clearAllMocks(); setActivePinia(createPinia())
    const next=useArchiveRecoveryStore()
    expect(next.rows).toHaveLength(0); expect(next.recoveryCount).toBe(2)
    expect(mocks.diagnose).not.toHaveBeenCalled(); expect(mocks.repair).not.toHaveBeenCalled()
    next.restore()
    expect(next.rows[0]).toMatchObject({password:'',resultPassword:'',resultPasswordRequired:true,outputDirectory:'D:/repair',extractDirectory:'D:/extract'})
    expect(next.repairable).toHaveLength(0)
    expect(next.completed).toBe(0)
    const reopened=mount(ArchiveRecoveryBatch,{props:{paths:[...next.sourcePaths]},global:{plugins:[getActivePinia()!],stubs:{Teleport:true,Transition:false}}})
    await flushPromises()
    expect(reopened.findAll('button').filter(button=>button.text()==='查看完整诊断').every(button=>button.attributes('disabled')!==undefined)).toBe(true)
    expect(await next.queue()).toBe(0)
    expect(next.rows[0].error).toContain('恢复结果密码')
    next.rows[0].resultPassword='recovered archive password'
    expect(await next.queue()).toBe(1)
    expect(useTaskStore().tasks[0]).toMatchObject({password:'recovered archive password',outputPath:'D:/extract'})
    expect(localStorage.getItem(ARCHIVE_RECOVERY_DRAFT_KEY)).not.toContain('recovered archive password')
    expect(await next.queue()).toBe(0)
    reopened.unmount()
  })

  it('does not queue a deleted recovered volume and lets the user recheck and repair the original', async () => {
    setActivePinia(createPinia())
    const store=useArchiveRecoveryStore()
    await store.load(['C:/a.rar','C:/b.zip'])
    store.rows[0].result={outputPath:'D:/a.part1.rar',outputFiles:['D:/a.part1.rar','D:/a.part2.rar'],recoveredFiles:1,recoveredDirectories:0,skippedEntries:[],verified:true,partial:false,directoryRebuilt:false,outputEncrypted:false}
    mocks.invoke.mockImplementation(async (_command,args) => {if(args?.path==='D:/a.part2.rar')throw Error('not found')})
    expect(await store.queue()).toBe(0)
    expect(useTaskStore().tasks).toHaveLength(0)
    expect(store.rows[0].error).toContain('已移动、删除或无法读取')
    store.forgetResult(store.rows[0])
    expect(store.rows[0].result).toBeUndefined()
    expect(store.rows[0].needsRecheck).toBe(true)
  })

  it('does not lose a saved workspace when new grouping fails and rejects replacing a running batch', async () => {
    setActivePinia(createPinia())
    const store=useArchiveRecoveryStore()
    await store.load(['C:/a.rar','C:/b.zip'])
    const id=store.rows[0].id
    mocks.group.mockRejectedValueOnce(new Error('folder unavailable'))
    await expect(store.load(['D:/new.zip'])).rejects.toThrow('folder unavailable')
    expect(store.rows[0].id).toBe(id)
    store.busy=true
    await expect(store.load(['D:/new.zip'])).rejects.toThrow('等待')
    store.busy=false
  })

  it('lets malformed previous-session records be discarded without starting work', async () => {
    localStorage.setItem(ARCHIVE_RECOVERY_DRAFT_KEY,'{"version":1,"rows":[{}]}')
    setActivePinia(createPinia())
    const store=useArchiveRecoveryStore()
    expect(store.saveError).toContain('草稿无法读取')
    store.discardPrevious()
    expect(localStorage.getItem(ARCHIVE_RECOVERY_DRAFT_KEY)).toBeNull()
    expect(mocks.diagnose).not.toHaveBeenCalled()
  })
})
