// Source investigation, deliberately outside CI and release gates. This is not
// evidence of method-3 interoperability. Never modify an archive method byte.
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'

let inspectOnly = false, helperPath = 'src-tauri/resources/alz-engine/long-alz.exe'
for (let i = 2; i < process.argv.length; i++) {
  if (process.argv[i] === '--inspect-only') inspectOnly = true
  else if (process.argv[i] === '--helper') {
    const value = process.argv[++i]
    assert.ok(value && !value.startsWith('--'), '--helper requires the recorded old helper path')
    helperPath = value
  } else assert.fail('Unknown option: ' + process.argv[i])
}
const base = path.resolve('test-results/alz-165/research')
const manifest = JSON.parse(readFileSync('docs/evidence/alz-method3-source-1.6.5/producer-probe.json', 'utf8'))
const helper = path.resolve(helperPath)
const sha = file => createHash('sha256').update(readFileSync(file)).digest('hex')
assert.equal(sha(path.join('docs/evidence/alz-method3-source-1.6.5', manifest.archiveFixture)), manifest.attempts[0].archiveSha256)
const source = path.join(base, 'size-source')
const seed = Buffer.concat([
  Buffer.from('Long ALZ original producer probe. Public self-authored text.\r\n'),
  Buffer.from(Array.from({ length: 95 }, (_, i) => i + 32)),
])
const payload = Buffer.concat(Array.from({ length: 100 }, () => seed))
const tree = folder => readdirSync(folder).sort().map(name => ({
  path: name, bytes: readFileSync(path.join(folder, name)).length, sha256: sha(path.join(folder, name)),
}))
const invoke = (tool, args, options = {}) => {
  const result = spawnSync(tool, args, { windowsHide: true, encoding: 'utf8', timeout: 30000, ...options })
  assert.ifError(result.error)
  assert.equal(result.status, 0, result.stdout + result.stderr)
}

if (!inspectOnly) {
  mkdirSync(source, { recursive: true })
  for (let i = 0; i < 16; i++) {
    const file = path.join(source, `size-mod-${String(i).padStart(2, '0')}.txt`)
    const bytes = payload.subarray(0, 4096 + i)
    if (existsSync(file)) assert.deepEqual(readFileSync(file), bytes)
    else writeFileSync(file, bytes)
  }
}
assert.deepEqual(tree(source), manifest.expected)
assert.equal(sha(helper), manifest.helperSha256, 'Use the recorded helper, or record a new investigation identity')

const folders = ['alzip55', 'alzip55eng', 'alzip56']
const results = []
for (const [index, original] of manifest.attempts.entries()) {
  const app = path.join(base, folders[index], 'app')
  const tool = path.join(app, 'ALZip.exe')
  assert.equal(sha(tool), original.executableSha256)
  assert.equal(sha(path.join(base, original.backupFilename)), original.installerSha256)
  const archive = path.join(base, folders[index] + '-all-size-residues.alz')
  const decoded = path.join(base, folders[index] + '-helper-decoded')
  if (!inspectOnly && !existsSync(archive)) invoke(tool, ['-a', path.join(source, '*.*'), archive], { cwd: app })
  const bytes = readFileSync(archive)
  assert.deepEqual(bytes.subarray(0, 4), Buffer.from('ALZ\x01'))
  const entries = []
  let position = 8
  while (bytes.subarray(position, position + 4).equals(Buffer.from('BLZ\x01'))) {
    const length = bytes.readUInt16LE(position + 4), flags = bytes[position + 11], width = flags >> 4
    assert.ok([1, 2, 4].includes(width), 'This investigation expects only small nonempty files')
    assert.equal(flags & 1, 0, 'This investigation is plain single-file ALZ only')
    let cursor = position + 13
    const method = bytes[cursor]
    const compressedSize = bytes.readUIntLE(cursor + 6, width)
    const uncompressedSize = bytes.readUIntLE(cursor + 6 + width, width)
    cursor += 6 + width * 2
    const name = bytes.subarray(cursor, cursor + length).toString('ascii')
    cursor += length
    assert.ok(cursor + compressedSize <= bytes.length - 16)
    entries.push({ path: name, method, uncompressedSize, compressedSize, sizeMod16: uncompressedSize % 16 })
    position = cursor + compressedSize
  }
  assert.equal(entries.length, 16)
  assert.deepEqual([...new Set(entries.map(e => e.sizeMod16))].sort((a, b) => a - b), Array.from({ length: 16 }, (_, i) => i))
  assert.deepEqual(bytes.subarray(position, position + 4), Buffer.from('CLZ\x01'))
  if (!inspectOnly && !existsSync(decoded)) invoke(helper, ['extract', archive], {
    input: JSON.stringify({ output: decoded, encoding: 'cp949' }),
  })
  assert.deepEqual(tree(decoded), manifest.expected)
  // Freshly generated bytes may differ due to source timestamps. Preserve the
  // old receipt; never silently rewrite original archive hashes as the same run.
  if (inspectOnly) {
    assert.equal(sha(archive), original.archiveSha256)
    assert.deepEqual(entries, original.entries)
  }
  results.push({ version: original.reportedFileVersion, methods: [...new Set(entries.map(e => e.method))], archiveSha256: sha(archive) })
}
console.log(JSON.stringify({ inspectOnly, method3Obtained: results.some(r => r.methods.includes(3)), defaultCommandOnly: true, results }, null, 2))
